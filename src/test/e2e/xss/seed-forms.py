#!/usr/bin/env python3
"""
LUT-33153 — stored XSS campaign for plugin-forms, the companion of seed-core.py: writes an XSS payload
into every descriptive text field of a form (form, steps, groups, questions, entries, choices,
messages) and into the text answers, each payload carrying the number of its field. The crawl
(pages-e2e.js with XSS_MARKERS) then reports every payload that executed or reached the DOM as markup.

The fields edited with a rich text editor get a rich payload instead: its formatting (<b>) must be
rendered, its script must not.

Usage: seed-forms.py <markers.json> [first-number]  > seed.sql   (then: mariadb <db> < seed.sql)
"""
import json
import sys

PLAIN = [
    # table, column, where clause, max length, origin note
    ("forms_form", "title", "1=1", 255, "form title"),
    ("forms_form", "description", "1=1", 255, "form description"),
    ("forms_form", "label_final_button", "1=1", 255, "form final button label"),
    ("forms_message", "label_end_message_button", "1=1", 255, "end message button label"),
    ("forms_step", "title", "1=1", 255, "step title"),
    ("forms_step", "description", "1=1", 255, "step description"),
    ("forms_group", "title", "1=1", 255, "group title"),
    ("forms_group", "iteration_add_label", "1=1", 255, "group add label"),
    ("forms_group", "iteration_remove_label", "1=1", 255, "group remove label"),
    ("forms_question", "title", "1=1", 255, "question title"),
    ("forms_question", "column_title", "1=1", 255, "question column title"),
    ("forms_question", "description", "1=1", 4000, "question description"),
    ("genatt_entry", "title", "1=1", 4000, "entry title"),
    ("genatt_entry", "help_message", "1=1", 4000, "entry help message"),
    ("genatt_entry", "error_message", "1=1", 4000, "entry error message"),
    ("genatt_entry", "comment",
     "id_type NOT IN (SELECT id_type FROM genatt_entry_type WHERE class_name = 'forms.entryTypeComment')", 4000, "entry comment"),
    ("genatt_field", "title", "code IN ('answer_choice', 'link')", 255, "choice title / terms of service link"),
    ("genatt_field", "comment", "code = 'answer_choice'", 4000, "choice comment"),
    ("genatt_field", "value", "code = 'placeholder'", 4000, "placeholder"),
    ("genatt_response", "response_value",
     "id_entry IN (SELECT id_entry FROM genatt_entry e JOIN genatt_entry_type t ON e.id_type = t.id_type"
     " WHERE t.class_name IN ('forms.entryTypeText', 'forms.entryTypeTextArea'))", 4000, "text answer"),
]

RICH = [
    ("forms_form", "unavailable_message", "1=1", 3000, "unavailable message (rich text)"),
    ("forms_message", "end_message", "1=1", 3000, "end message (rich text)"),
    ("forms_group", "description", "1=1", 512, "group description (rich text)"),
    ("genatt_entry", "comment",
     "id_type IN (SELECT id_type FROM genatt_entry_type WHERE class_name = 'forms.entryTypeComment')", 4000, "comment entry (rich text)"),
    ("genatt_field", "value", "code = 'tos'", 4000, "terms of service (rich text)"),
]


def plain(n, size):
    short = "x'\"><svg/onload=alert(%d)>" % n
    full = short + "</script><script>alert(%d)</script>';alert(%d);//" % (n, n)
    return full if len(full) <= size else short


def rich(n):
    return "<p>rich <b>bold%d</b></p><img src=x onerror=alert(%d)><a href=\"javascript:alert(%d)\">link</a><svg/onload=alert(%d)>" % (n, n, n, n)


def sql(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "''") + "'"


markers = {}
out = ["-- generated by seed-forms.py"]
n = int(sys.argv[2]) if len(sys.argv) > 2 else 300
for table, column, where, size, note in PLAIN:
    n += 1
    markers[n] = "%s.%s (%s)" % (table, column, note)
    out.append("UPDATE %s SET %s = %s WHERE %s;" % (table, column, sql(plain(n, size)), where))
for table, column, where, size, note in RICH:
    n += 1
    markers[n] = "%s.%s (%s)" % (table, column, note)
    out.append("UPDATE %s SET %s = %s WHERE %s;" % (table, column, sql(rich(n)), where))
n += 1
markers[n] = "forms_form.return_url (back link of the end page)"
out.append("UPDATE forms_form SET return_url = 'javascript:alert(%d)' WHERE 1=1;" % n)

json.dump(markers, open(sys.argv[1], "w"), indent=1)
print("\n".join(out))
