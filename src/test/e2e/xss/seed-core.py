#!/usr/bin/env python3
"""
LUT-33153 — stored XSS campaign: writes an XSS payload into every descriptive text field of the
lutece-core database that a page may print, each payload carrying a number that identifies its
field. The crawl (pages-e2e.js with XSS_MARKERS) then reports every payload that executed or that
reached the DOM as markup.

Usage: seed-core.py <markers.json>  > seed.sql   (then: mariadb <db> < seed.sql)

Payloads are short because some columns are (core_page.name is 50 characters). One payload breaks
out of a text node, a double- or single-quoted attribute and a JavaScript string at once:

    x'"><svg/onload=alert(N)>

The longer columns also get a script element and a JavaScript string breakout.
"""
import json
import sys

FIELDS = [
    # table, column, where clause, max length, origin note
    ("core_admin_user", "first_name", "1=1", 100, "back-office user first name"),
    ("core_admin_user", "last_name", "1=1", 100, "back-office user last name"),
    ("core_admin_mailinglist", "name", "1=1", 100, "mailing list name"),
    ("core_admin_mailinglist", "description", "1=1", 255, "mailing list description"),
    ("core_admin_role", "role_description", "1=1", 100, "RBAC role description"),
    ("core_admin_security_header", "description", "1=1", 1024, "security header description"),
    ("core_admin_workgroup", "workgroup_description", "1=1", 255, "workgroup description"),
    ("core_page", "name", "1=1", 50, "page name"),
    ("core_page", "description", "1=1", 4000, "page description"),
    ("core_page", "meta_keywords", "1=1", 255, "page meta keywords"),
    ("core_page", "meta_description", "1=1", 255, "page meta description"),
    ("core_page_template", "description", "1=1", 50, "page template description"),
    ("core_portlet_template", "description", "1=1", 255, "portlet template description"),
    ("core_role", "role_description", "1=1", 255, "front-office role description"),
    ("core_theme", "theme_description", "1=1", 255, "theme description"),
]

DATASTORE = [
    "portal.site.site_property.name",
    "portal.site.site_property.email",
    "portal.site.site_property.meta.author",
    "portal.site.site_property.meta.copyright",
    "portal.site.site_property.meta.description",
    "portal.site.site_property.meta.keywords",
    "portal.theme.site_property.banner.title",
    "portal.theme.site_property.banner.credits",
    "portal.theme.site_property.bannerMessage.Title",
    "portal.theme.site_property.forms.labelInfoResponse",
    "portal.theme.site_property.formvalidation.msg.required",
    "portal.theme.site_property.formvalidation.msg.email",
    "portal.theme.site_property.menu.logo.alt",
    "portal.theme.site_property.layout.footer.logoFooterAlt",
]


def payload(n, size):
    short = "x'\"><svg/onload=alert(%d)>" % n
    full = short + "</script><script>alert(%d)</script>';alert(%d);//" % (n, n)
    return full if len(full) <= size else short


def sql(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "''") + "'"


markers = {}
out = ["-- generated by seed-core.py"]
n = 100
for table, column, where, size, note in FIELDS:
    n += 1
    markers[n] = "%s.%s (%s)" % (table, column, note)
    out.append("UPDATE %s SET %s = %s WHERE %s;" % (table, column, sql(payload(n, size)), where))
for key in DATASTORE:
    n += 1
    markers[n] = "core_datastore %s" % key
    out.append("UPDATE core_datastore SET entity_value = %s WHERE entity_key = %s;" % (sql(payload(n, 4000)), sql(key)))

json.dump(markers, open(sys.argv[1], "w"), indent=1)
print("\n".join(out))
