package fr.paris.lutece.portal.web.portlet;

import org.junit.jupiter.api.Test;

import fr.paris.lutece.portal.business.portlet.Portlet;
import fr.paris.lutece.portal.service.portal.PortalService;
import fr.paris.lutece.portal.service.security.ISecurityTokenService;
import fr.paris.lutece.portal.service.security.SecurityTokenHandler;
import fr.paris.lutece.portal.web.constants.Parameters;
import fr.paris.lutece.test.LuteceTestCase;
import fr.paris.lutece.test.mocks.MockHttpServletRequest;
import jakarta.inject.Inject;
import jakarta.servlet.http.HttpServletRequest;

/**
 * The common data of a portlet are saved only with the token of the common form
 */
public class PortletJspBeanTokenTest extends LuteceTestCase
{
    private static final String NAME = "junit portlet";

    private @Inject ISecurityTokenService _securityTokenService;

    /**
     * A portlet bean with nothing specific
     */
    private static final class TestPortletJspBean extends PortletJspBean
    {
        private static final long serialVersionUID = 1L;

        @Override
        public String getCreate( HttpServletRequest request )
        {
            return null;
        }

        @Override
        public String doCreate( HttpServletRequest request )
        {
            return null;
        }

        @Override
        public String getModify( HttpServletRequest request )
        {
            return null;
        }

        @Override
        public String doModify( HttpServletRequest request )
        {
            return null;
        }

        String setCommonData( HttpServletRequest request, Portlet portlet )
        {
            return setPortletCommonData( request, portlet );
        }
    }

    /**
     * A portlet whose content is not generated by XSL
     */
    private static final class TestPortlet extends Portlet
    {
        @Override
        public void remove( )
        {
        }

        @Override
        public boolean isContentGeneratedByXmlAndXsl( )
        {
            return false;
        }

        @Override
        public String getXml( HttpServletRequest request )
        {
            return null;
        }

        @Override
        public String getXmlDocument( HttpServletRequest request )
        {
            return null;
        }
    }

    private MockHttpServletRequest newRequest( )
    {
        MockHttpServletRequest request = new MockHttpServletRequest( );
        request.setParameter( Parameters.PORTLET_NAME, NAME );
        request.setParameter( Parameters.ORDER, "1" );
        request.setParameter( Parameters.COLUMN, "1" );
        request.setParameter( Parameters.ACCEPT_ALIAS, "0" );
        request.setParameter( Parameters.DISPLAY_PORTLET_TITLE, "0" );
        request.setParameter( "page_id", Integer.toString( PortalService.getRootPageId( ) ) );
        return request;
    }

    @Test
    public void testCreationWithoutToken( )
    {
        TestPortlet portlet = new TestPortlet( );

        assertNotNull( new TestPortletJspBean( ).setCommonData( newRequest( ), portlet ) );
        assertNull( portlet.getName( ) );
    }

    @Test
    public void testCreationWithToken( )
    {
        MockHttpServletRequest request = newRequest( );
        request.setParameter( SecurityTokenHandler.MARK_CSRF_TOKEN, _securityTokenService.getToken( request, "admin/portlet/create_portlet.html" ) );
        TestPortlet portlet = new TestPortlet( );

        assertNull( new TestPortletJspBean( ).setCommonData( request, portlet ) );
        assertEquals( NAME, portlet.getName( ) );
    }

    @Test
    public void testModificationNeedsModificationToken( )
    {
        MockHttpServletRequest request = newRequest( );
        request.setParameter( SecurityTokenHandler.MARK_CSRF_TOKEN, _securityTokenService.getToken( request, "admin/portlet/create_portlet.html" ) );
        TestPortlet portlet = new TestPortlet( );
        portlet.setId( 1 );

        assertNotNull( new TestPortletJspBean( ).setCommonData( request, portlet ) );
    }
}
